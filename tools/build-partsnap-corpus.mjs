import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const importDir = path.resolve('data/partsnap/imports');
const generatedDir = path.resolve('data/partsnap/generated');
const runtimePath = path.resolve('functions/_shared/partsnap-generated-families.mjs');
const manifestPath = path.join(generatedDir, 'partsnap-corpus-build-report.json');

function repoPath(file) {
  return path.relative(process.cwd(), file).split(path.sep).join('/');
}

const sourceRegistry = JSON.parse(await readFile('data/partsnap/reference-sources.json', 'utf8'));
const sourceIds = new Set((sourceRegistry.sources || []).map((source) => source.id));
const importFiles = (await readdir(importDir))
  .filter((file) => file.endsWith('.json'))
  .sort()
  .map((file) => path.join(importDir, file));
const importPayloads = await Promise.all(importFiles.map(async (file) => ({
  file,
  payload: JSON.parse(await readFile(file, 'utf8')),
})));
const families = importPayloads.flatMap(({ file, payload }) =>
  (Array.isArray(payload.families) ? payload.families : []).map((family) => ({
    ...family,
    __importFile: repoPath(file),
    __importStatus: payload.status || '',
  })),
);

const required = ['id', 'sourceIds', 'manufacturer', 'category', 'component', 'modelFamilies', 'aliases', 'visualClues', 'requiredProof', 'lookalikeWarnings'];
const errors = [];
const ids = new Set();

function cleanString(value, max = 240) {
  return String(value || '').replace(/[\u0000-\u001f\u007f]/g, '').trim().slice(0, max);
}

function cleanList(value, maxItems = 12, maxChars = 180) {
  return Array.isArray(value)
    ? value.map((item) => cleanString(item, maxChars)).filter(Boolean).slice(0, maxItems)
    : [];
}

const normalized = families.map((row, index) => {
  for (const key of required) {
    if (row[key] == null || (Array.isArray(row[key]) && row[key].length === 0) || row[key] === '') {
      errors.push(`families[${index}].${key} is required`);
    }
  }
  const id = cleanString(row.id, 120);
  if (ids.has(id)) errors.push(`duplicate family id: ${id}`);
  ids.add(id);

  const rowSourceIds = cleanList(row.sourceIds, 8, 120);
  for (const sourceId of rowSourceIds) {
    if (!sourceIds.has(sourceId)) errors.push(`${id} uses unknown sourceId ${sourceId}`);
  }

  return {
    id,
    sourceIds: rowSourceIds,
    manufacturer: cleanString(row.manufacturer, 120),
    category: cleanString(row.category, 80),
    component: cleanString(row.component, 220),
    modelFamilies: cleanList(row.modelFamilies, 16, 120),
    aliases: cleanList(row.aliases, 18, 100),
    visualClues: cleanList(row.visualClues, 12, 140),
    requiredProof: cleanList(row.requiredProof, 12, 140),
    lookalikeWarnings: cleanList(row.lookalikeWarnings, 6, 220),
    importFile: cleanString(row.__importFile, 220),
    importStatus: cleanString(row.__importStatus, 80),
  };
});

if (errors.length) {
  console.error(JSON.stringify({ ok: false, errors }, null, 2));
  process.exit(1);
}

const moduleBody = [
  '// Generated by tools/build-partsnap-corpus.mjs. Edit data/partsnap/imports/seed-expansion.json instead.',
  `export const GENERATED_FAMILY_IMPORTS = ${JSON.stringify(normalized, null, 2)};`,
  '',
].join('\n');

await mkdir(generatedDir, { recursive: true });
await writeFile(runtimePath, moduleBody, 'utf8');

const byCategory = new Map();
const byManufacturer = new Map();
for (const row of normalized) {
  byCategory.set(row.category, (byCategory.get(row.category) || 0) + 1);
  byManufacturer.set(row.manufacturer, (byManufacturer.get(row.manufacturer) || 0) + 1);
}
const toRows = (map) => Array.from(map.entries())
  .map(([name, count]) => ({ name, count }))
  .sort((a, b) => b.count - a.count || a.name.localeCompare(b.name));

const report = {
  ok: true,
  generatedAt: new Date().toISOString(),
  importDir: repoPath(importDir),
  importFiles: importFiles.map(repoPath),
  runtimePath: repoPath(runtimePath),
  importFileCount: importFiles.length,
  importedFamilyCount: normalized.length,
  coverage: {
    byCategory: toRows(byCategory),
    byManufacturer: toRows(byManufacturer),
  },
  guardrail: 'Generated rows are source-backed family candidates only. They are not exact-fit or partner-verified claims.',
};

await writeFile(manifestPath, `${JSON.stringify(report, null, 2)}\n`, 'utf8');
console.log(JSON.stringify(report, null, 2));
